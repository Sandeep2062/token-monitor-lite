"""Generate Slint gettext bundles from the upstream i18n catalogue.

The source strings are the upstream renderer's own, copied verbatim from
`token-monitor/src/electron/renderer/i18n.js`. Nothing here invents a
translation: a key the upstream does not have is a hard error, so a typo in a
Slint `@tr()` call cannot silently produce English text in a Japanese UI.

Layout expected by `slint_build::CompilerConfiguration::with_bundled_translations`:

    ui/i18n/<locale>/LC_MESSAGES/<crate-name>.po

Run from the repository root:

    python scripts/generate-settings-i18n.py
"""

from __future__ import annotations

import io
import json
import os
import subprocess
import sys

LOCALES = ["en", "zh-TW", "zh-CN", "ko", "ja", "pt-BR"]
# The `.po` file must be named after the crate; Slint looks it up by that name.
CRATE = "token-monitor-lite"

# Every key the native settings surface uses. Each one must exist upstream.
KEYS = [
    "settings.appearance.title",
    "settings.appearance.reduceMotion",
    "settings.appearance.reduceMotionNote",
    "settings.appearance.motion.system",
    "settings.appearance.motion.on",
    "settings.appearance.motion.off",
    "settings.appearance.textSize",
    "settings.language.title",
    "settings.language.label",
    "settings.language.auto",
    "settings.language.english",
    "settings.language.zhTW",
    "settings.language.zhCN",
    "settings.language.korean",
    "settings.language.japanese",
    "settings.language.portugueseBR",
    "settings.currency.label",
    "settings.currency.usd",
    "settings.currency.twd",
    "settings.currency.hkd",
    "settings.currency.cny",
    "settings.currency.rateMode",
    "settings.currency.modeAuto",
    "settings.currency.modeManual",
    "settings.currency.rateDefault",
]

# Native-only keys: sections the upstream settings sheet does not name because
# its General/Appearance tabs are labelled elsewhere. Marked in the header so the
# provenance stays obvious.
NATIVE_ONLY = {
    "General": "General",
    "Appearance": "Appearance",
    "Currency": "Currency",
    "Language": "Language",
    "Settings": "Settings",
    "Theme": "Theme",
    "Light": "Light",
    "Dark": "Dark",
    "System": "System",
    "Density": "Density",
    "Comfortable": "Comfortable",
    "Compact": "Compact",
    "Display currency": "Display currency",
    "Display only. Accounting stays in USD.": (
        "Display only. Accounting stays in USD."
    ),
}


def load_upstream() -> dict[str, dict[str, str]]:
    script = (
        "const path=require('path');"
        "const api=require(path.join(process.cwd(),"
        "'token-monitor/src/electron/renderer/i18n.js'));"
        "process.stdout.write(JSON.stringify(api.MESSAGES));"
    )
    result = subprocess.run(
        ["node", "-e", script],
        capture_output=True,
        check=True,
        cwd=os.getcwd(),
    )
    return json.loads(result.stdout.decode("utf-8"))


def po_escape(text: str) -> str:
    # gettext PO quoting: backslash, double quote, and real newlines.
    return (
        text.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\t", "\\t")
    )


def render_po(locale: str, messages: dict[str, str], upstream: dict[str, dict[str, str]]) -> str:
    out = io.StringIO()
    out.write(
        "# Generated by scripts/generate-settings-i18n.py from\n"
        "# token-monitor/src/electron/renderer/i18n.js. Do not edit by hand.\n"
        "#\n"
        "# msgid  the English source string used in ui/app.slint\n"
        "# msgstr  the upstream string for this locale\n"
        "#\n"
        f"# Locale: {locale}\n"
        "msgid \"\"\n"
        "msgstr \"\"\n"
        "\"Content-Type: text/plain; charset=UTF-8\\n\"\n"
        "\"Language: " + locale + "\\n\"\n"
    )
    # Stable order so regeneration produces no diff noise.
    for msgid in sorted(messages):
        msgstr = messages[msgid]
        out.write("\n")
        out.write(f"msgid \"{po_escape(msgid)}\"\n")
        out.write(f"msgstr \"{po_escape(msgstr)}\"\n")
    return out.getvalue()


def main() -> int:
    upstream = load_upstream()
    missing = [locale for locale in LOCALES if locale not in upstream]
    if missing:
        print(f"upstream is missing locales: {missing}", file=sys.stderr)
        return 1

    # msgid -> msgstr for this locale.
    tables: dict[str, dict[str, str]] = {locale: {} for locale in LOCALES}
    for key in KEYS:
        for locale in LOCALES:
            value = upstream[locale].get(key)
            if value is None:
                print(f"upstream {locale} has no key {key!r}", file=sys.stderr)
                return 1
            # The msgid is the English source string, not the dotted key: that is
            # what `@tr("…")` in Slint matches on.
            msgid = upstream["en"][key]
            tables[locale][msgid] = value

    for msgid, english in NATIVE_ONLY.items():
        for locale in LOCALES:
            tables[locale].setdefault(msgid, english)

    for locale in LOCALES:
        directory = os.path.join("ui", "i18n", locale, "LC_MESSAGES")
        os.makedirs(directory, exist_ok=True)
        path = os.path.join(directory, f"{CRATE}.po")
        text = render_po(locale, tables[locale], upstream)
        with io.open(path, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)
        print(f"{path}: {len(tables[locale])} messages")

    # English is the source language: every msgstr must equal its msgid, or a
    # typo in the table would silently translate English.
    for msgid, msgstr in tables["en"].items():
        if msgid != msgstr:
            print(f"en msgstr differs from msgid: {msgid!r} -> {msgstr!r}", file=sys.stderr)
            return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
